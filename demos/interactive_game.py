def on_press(key):
    #try:
    #    print(f"Alphanumeric key pressed: {key.char}")
    #except AttributeError:
    #    print(f"Special key pressed: {key}")
    x = position[0]
    y = position[1]
    if key == Key.up:
        position[1] = (3 + y - 1) % 3
    if key == Key.down:
        position[1] = (y + 1) % 3
    if key == Key.right:
        position[0] = (x + 1) % 3
    if key == Key.left:
        position[0] = (3 + x - 1) % 3
    print_pos(position)

def print_pos(position):
    os.system('clear')
    for y in range(3):
        for x in range(3):
            if [x, y] == position:
                print("x", end="")
            else:
                print(" ", end="")
        print()
    

def on_release(key):
    #print(f"Key released: {key}")
    # Stop listener if Escape is pressed
    if key == keyboard.Key.esc:
        return False

print_pos(position)

# Start listening non-blockingly in the background
listener = keyboard.Listener(on_press=on_press, on_release=on_release)
listener.start()

